# =============================================================================
# S.H.I.E.L.D. Core Engine — Alert System
# Generates structured alert objects with full metadata for each detection.
#
# Alert levels map to the four pipeline stages:
#   Stage 1: ALL CLEAR    (green)  — quiet Sun
#   Stage 2: WATCH        (amber)  — pre-flare heating detected
#   Stage 3: FORECAST     (orange) — flare anticipated, not yet confirmed
#   Stage 4: CONFIRMED    (red)    — flare onset confirmed
# =============================================================================

import logging
from dataclasses import dataclass, field, asdict
from datetime import datetime
from enum import IntEnum
from typing import List, Optional, Dict, Any

import pandas as pd

from config.settings import STAGES

logger = logging.getLogger(__name__)


class AlertLevel(IntEnum):
    """Alert levels corresponding to the four pipeline stages."""
    ALL_CLEAR = 1
    WATCH = 2
    FORECAST_ALERT = 3
    NOWCAST_CONFIRMED = 4


@dataclass
class Alert:
    """A single alert generated by the detection pipeline."""

    alert_id: str                         # Unique identifier
    timestamp: pd.Timestamp               # When the alert was issued
    level: AlertLevel                     # Alert level (1-4)
    stage_name: str                       # Human-readable stage name
    status: str                           # Status string (e.g., "FORECAST ALERT")

    # Detection details
    trigger_source: str                   # 'solexs', 'hel1os', or 'pipeline'
    provisional_class: str                # Estimated flare class
    confidence: float                     # Confidence score (0-1)

    # Measurements
    solexs_flux: float = 0.0              # SoLEXS flux at alert time
    solexs_derivative: float = 0.0        # SoLEXS derivative at alert time
    hel1os_flux: float = 0.0              # HEL1OS flux at alert time
    hel1os_sigma: float = 0.0             # HEL1OS sigma above baseline
    neupert_correlation: float = 0.0      # Neupert cross-check correlation

    # Timing
    sustained_duration_s: float = 0.0     # How long conditions were sustained
    time_since_last_alert_s: float = 0.0  # Gap since previous alert

    # Metadata
    event_id: str = ""                    # Which event this belongs to
    notes: str = ""                       # Additional notes

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary for serialization."""
        d = asdict(self)
        d['timestamp'] = str(self.timestamp)
        d['level'] = int(self.level)
        return d

    def summary(self) -> str:
        """One-line summary for logging."""
        return (f"[{self.status}] {self.timestamp} | "
                f"class~{self.provisional_class} | "
                f"conf={self.confidence:.2f} | "
                f"src={self.trigger_source}")


@dataclass
class AlertLog:
    """Chronological log of all alerts for an event."""

    event_id: str
    alerts: List[Alert] = field(default_factory=list)

    # Stage transition timestamps
    stage1_start: Optional[pd.Timestamp] = None   # ALL CLEAR
    stage2_start: Optional[pd.Timestamp] = None   # WATCH
    stage3_start: Optional[pd.Timestamp] = None   # FORECAST ALERT
    stage4_start: Optional[pd.Timestamp] = None   # NOWCAST CONFIRMED

    # The core deliverable
    stage3_to_4_gap_s: Optional[float] = None

    def add_alert(self, alert: Alert):
        """Add an alert to the log and update stage timestamps."""
        self.alerts.append(alert)

        # Track first occurrence of each stage
        if alert.level == AlertLevel.ALL_CLEAR and self.stage1_start is None:
            self.stage1_start = alert.timestamp
        elif alert.level == AlertLevel.WATCH and self.stage2_start is None:
            self.stage2_start = alert.timestamp
        elif alert.level == AlertLevel.FORECAST_ALERT and self.stage3_start is None:
            self.stage3_start = alert.timestamp
        elif alert.level == AlertLevel.NOWCAST_CONFIRMED and self.stage4_start is None:
            self.stage4_start = alert.timestamp

        # Update gap measurement
        if self.stage3_start and self.stage4_start:
            self.stage3_to_4_gap_s = (
                self.stage4_start - self.stage3_start
            ).total_seconds()

        logger.info(f"  {alert.summary()}")

    def get_alerts_by_level(self, level: AlertLevel) -> List[Alert]:
        """Get all alerts at a specific level."""
        return [a for a in self.alerts if a.level == level]

    def get_current_stage(self) -> int:
        """Get the highest stage reached."""
        if not self.alerts:
            return 1
        return max(a.level for a in self.alerts)

    def print_summary(self):
        """Print a formatted summary of the alert log."""
        print(f"\n  Alert Log for {self.event_id}")
        print(f"  {'='*55}")
        print(f"  Total alerts: {len(self.alerts)}")

        for level in AlertLevel:
            count = len(self.get_alerts_by_level(level))
            stage_info = STAGES.get(int(level), {})
            name = stage_info.get('name', str(level))
            print(f"    Stage {int(level)} ({name}): {count} alert(s)")

        if self.stage3_start:
            print(f"\n  First FORECAST ALERT  : {self.stage3_start}")
        if self.stage4_start:
            print(f"  First NOWCAST CONFIRMED: {self.stage4_start}")
        if self.stage3_to_4_gap_s is not None:
            gap = self.stage3_to_4_gap_s
            print(f"  Stage 3->4 gap        : {gap:.1f}s ({gap/60:.1f} min)")

    def to_dataframe(self) -> pd.DataFrame:
        """Convert alert log to a DataFrame for analysis."""
        if not self.alerts:
            return pd.DataFrame()
        return pd.DataFrame([a.to_dict() for a in self.alerts])


def create_alert(
    level: AlertLevel,
    timestamp: pd.Timestamp,
    trigger_source: str,
    event_id: str = "",
    alert_count: int = 0,
    **kwargs,
) -> Alert:
    """Factory function to create a properly formatted Alert."""
    stage_info = STAGES.get(int(level), {})

    return Alert(
        alert_id=f"{event_id}_A{alert_count:04d}",
        timestamp=timestamp,
        level=level,
        stage_name=stage_info.get('name', f'STAGE {int(level)}'),
        status=stage_info.get('status', f'STAGE {int(level)}'),
        trigger_source=trigger_source,
        event_id=event_id,
        **kwargs,
    )
